#pragma once

#include "ImGui/Window.hpp"
#include "InputSystem.hpp"
#include <GLFW/glfw3.h>
#include <imgui.h>
#include <memory>
#include <string>

namespace Editor {
class WindowChangeKeybind : public Window {
public:
  WindowChangeKeybind() {
    instance = this;
    isOpen = false;
  }
  ~WindowChangeKeybind() {
    if (instance == this) {
      instance = nullptr;
    }
  }

  std::string GetName() override { return "Change Keybind"; }

  static void OpenFor(std::shared_ptr<Engine::Keybind> kb) {
    if (!kb)
      return;
    targetKeybind = kb;
    isListening = true;
    if (instance) {
      instance->Open();
    }
  }

  inline static WindowChangeKeybind *instance = nullptr;

protected:
  inline static std::shared_ptr<Engine::Keybind> targetKeybind = nullptr;
  inline static bool isListening = false;

  void draw() override {
    ImGui::SetNextWindowSize(ImVec2(380, 220), ImGuiCond_FirstUseEver);
    if (!ImGui::Begin(GetName().c_str(), &isOpen,
                      ImGuiWindowFlags_NoCollapse)) {
      ImGui::End();
      return;
    }

    // Only stay open if a keybind is actively being changed
    if (!isOpen || !targetKeybind) {
      Close();
      targetKeybind = nullptr;
      isListening = false;
      ImGui::End();
      return;
    }

    ImGui::Text("Action: %s", targetKeybind->name.c_str());
    ImGui::TextDisabled("Default: %s",
                        FormatKeyCombo(targetKeybind->default_key, 0).c_str());
    ImGui::Separator();

    ImGuiIO &io = ImGui::GetIO();
    std::string buttonText;

    if (isListening) {
      buttonText = "[";
      if (io.KeyCtrl)
        buttonText += "Ctrl + ";
      if (io.KeyShift)
        buttonText += "Shift + ";
      if (io.KeyAlt)
        buttonText += "Alt + ";
      buttonText += "...]";

      ImGui::PushStyleColor(ImGuiCol_Button, ImVec4(0.85f, 0.45f, 0.10f, 1.0f));
      ImGui::PushStyleColor(ImGuiCol_ButtonHovered,
                            ImVec4(0.95f, 0.55f, 0.15f, 1.0f));
    } else {
      buttonText = FormatKeyCombo(targetKeybind->key, targetKeybind->mods);
    }

    ImGui::TextUnformatted("Binding:");
    ImGui::SameLine();
    if (ImGui::Button((buttonText + "##key_button").c_str(), ImVec2(200, 32))) {
      isListening = !isListening;
    }

    if (isListening) {
      ImGui::PopStyleColor(2);
    }

    ImGui::Spacing();

    // Reset to Default button is available when changing
    if (ImGui::Button("Reset to Default")) {
      Rebind(targetKeybind, targetKeybind->default_key, 0);
      isListening = false;
      targetKeybind = nullptr;
      Close();
      ImGui::End();
      return;
    }

    ImGui::SameLine();
    if (ImGui::Button("Cancel")) {
      isListening = false;
      targetKeybind = nullptr;
      Close();
      ImGui::End();
      return;
    }

    if (isListening) {
      ImGui::Spacing();
      ImGui::TextColored(ImVec4(0.9f, 0.8f, 0.2f, 1.0f),
                         "Press any key (modifiers will be captured)...");
      ImGui::TextDisabled("Press Escape to cancel.");

      for (int k = ImGuiKey_NamedKey_BEGIN; k < ImGuiKey_NamedKey_END; ++k) {
        ImGuiKey imguiKey = static_cast<ImGuiKey>(k);

        if (IsModifierKey(imguiKey)) {
          continue;
        }

        if (ImGui::IsKeyPressed(imguiKey, false)) {
          if (imguiKey == ImGuiKey_Escape && !io.KeyCtrl && !io.KeyShift &&
              !io.KeyAlt) {
            isListening = false;
            targetKeybind = nullptr;
            Close();
            break;
          }

          int glfwKey = ImGuiKeyToGlfwKey(imguiKey);
          if (glfwKey != GLFW_KEY_UNKNOWN) {
            int capturedMods = 0;
            if (io.KeyShift)
              capturedMods |= GLFW_MOD_SHIFT;
            if (io.KeyCtrl)
              capturedMods |= GLFW_MOD_CONTROL;
            if (io.KeyAlt)
              capturedMods |= GLFW_MOD_ALT;

            Rebind(targetKeybind, glfwKey, capturedMods);
            isListening = false;
            targetKeybind = nullptr;
            Close();
            break;
          }
        }
      }
    }

    ImGui::End();
  }

  static bool IsModifierKey(ImGuiKey key) {
    return key == ImGuiKey_LeftCtrl || key == ImGuiKey_RightCtrl ||
           key == ImGuiKey_LeftShift || key == ImGuiKey_RightShift ||
           key == ImGuiKey_LeftAlt || key == ImGuiKey_RightAlt ||
           key == ImGuiKey_LeftSuper || key == ImGuiKey_RightSuper;
  }

  // generated by gemini
  static int ImGuiKeyToGlfwKey(ImGuiKey key) {
    if (key >= ImGuiKey_A && key <= ImGuiKey_Z)
      return GLFW_KEY_A + (key - ImGuiKey_A);
    if (key >= ImGuiKey_0 && key <= ImGuiKey_9)
      return GLFW_KEY_0 + (key - ImGuiKey_0);
    if (key >= ImGuiKey_F1 && key <= ImGuiKey_F12)
      return GLFW_KEY_F1 + (key - ImGuiKey_F1);
    if (key >= ImGuiKey_Keypad0 && key <= ImGuiKey_Keypad9)
      return GLFW_KEY_KP_0 + (key - ImGuiKey_Keypad0);

    switch (key) {
    case ImGuiKey_Space:
      return GLFW_KEY_SPACE;
    case ImGuiKey_Enter:
      return GLFW_KEY_ENTER;
    case ImGuiKey_Escape:
      return GLFW_KEY_ESCAPE;
    case ImGuiKey_Tab:
      return GLFW_KEY_TAB;
    case ImGuiKey_Backspace:
      return GLFW_KEY_BACKSPACE;
    case ImGuiKey_Insert:
      return GLFW_KEY_INSERT;
    case ImGuiKey_Delete:
      return GLFW_KEY_DELETE;
    case ImGuiKey_RightArrow:
      return GLFW_KEY_RIGHT;
    case ImGuiKey_LeftArrow:
      return GLFW_KEY_LEFT;
    case ImGuiKey_DownArrow:
      return GLFW_KEY_DOWN;
    case ImGuiKey_UpArrow:
      return GLFW_KEY_UP;
    case ImGuiKey_PageUp:
      return GLFW_KEY_PAGE_UP;
    case ImGuiKey_PageDown:
      return GLFW_KEY_PAGE_DOWN;
    case ImGuiKey_Home:
      return GLFW_KEY_HOME;
    case ImGuiKey_End:
      return GLFW_KEY_END;
    case ImGuiKey_CapsLock:
      return GLFW_KEY_CAPS_LOCK;
    case ImGuiKey_ScrollLock:
      return GLFW_KEY_SCROLL_LOCK;
    case ImGuiKey_NumLock:
      return GLFW_KEY_NUM_LOCK;
    case ImGuiKey_PrintScreen:
      return GLFW_KEY_PRINT_SCREEN;
    case ImGuiKey_Pause:
      return GLFW_KEY_PAUSE;
    case ImGuiKey_Minus:
      return GLFW_KEY_MINUS;
    case ImGuiKey_Equal:
      return GLFW_KEY_EQUAL;
    case ImGuiKey_LeftBracket:
      return GLFW_KEY_LEFT_BRACKET;
    case ImGuiKey_RightBracket:
      return GLFW_KEY_RIGHT_BRACKET;
    case ImGuiKey_Backslash:
      return GLFW_KEY_BACKSLASH;
    case ImGuiKey_Semicolon:
      return GLFW_KEY_SEMICOLON;
    case ImGuiKey_Apostrophe:
      return GLFW_KEY_APOSTROPHE;
    case ImGuiKey_Comma:
      return GLFW_KEY_COMMA;
    case ImGuiKey_Period:
      return GLFW_KEY_PERIOD;
    case ImGuiKey_Slash:
      return GLFW_KEY_SLASH;
    case ImGuiKey_GraveAccent:
      return GLFW_KEY_GRAVE_ACCENT;
    default:
      return GLFW_KEY_UNKNOWN;
    }
  }

  static std::string GetGlfwKeyName(int key, int scancode = 0) {
    if (key <= 0)
      return "None";
    if (scancode == 0)
      scancode = glfwGetKeyScancode(key);
    const char *name = glfwGetKeyName(key, scancode);
    return name ? name : "Unknown";
  }

  static std::string FormatKeyCombo(int key, int mods) {
    if (key <= 0)
      return "None";
    std::string str = "";
    if (mods & GLFW_MOD_CONTROL)
      str += "Ctrl + ";
    if (mods & GLFW_MOD_SHIFT)
      str += "Shift + ";
    if (mods & GLFW_MOD_ALT)
      str += "Alt + ";
    str += GetGlfwKeyName(key);
    return str;
  }

  static void Rebind(std::shared_ptr<Engine::Keybind> kb, int newKey,
                     int newMods) {
    if (!kb)
      return;
    auto input = Engine::InputSystem::instance;

    input->ChangeKeybind(kb->name, kb->key, newKey, newMods);
  }
};

} // namespace Editor
